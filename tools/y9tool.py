#!/usr/bin/env python3
"""
Y9 PRO V5 - config tool (runs on YOUR device; private keys never go to GitHub).

  python tools/y9tool.py init --repo USER/y9-app           # once: creates keys/ and keys.properties
  python tools/y9tool.py set-password config/config.json   # stores a salted hash, never the password
  python tools/y9tool.py build config/config.json          # writes site/config.enc.json (encrypted + signed)
  python tools/y9tool.py open site/config.enc.json         # decrypt + verify, for checking
  python tools/y9tool.py props                             # re-create keys.properties from keys/
"""
import argparse, base64, datetime, getpass, hashlib, json, os, sys, time

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec, rsa
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.serialization import pkcs12
from cryptography.x509.oid import NameOID

PBKDF2_ITERATIONS = 120000


def b64(b: bytes) -> str:
    return base64.b64encode(b).decode()


def read(path, mode="r"):
    with open(path, mode) as f:
        return f.read()


def write_secret(path, data, mode="w"):
    with open(path, mode) as f:
        f.write(data)
    try:
        os.chmod(path, 0o600)
    except OSError:
        pass


def load_keys(keys_dir):
    priv = serialization.load_pem_private_key(read(os.path.join(keys_dir, "sign_private.pem"), "rb"), password=None)
    aes = base64.b64decode(read(os.path.join(keys_dir, "aes.key")).strip())
    return priv, aes


def make_props(keys_dir, props_path):
    """keys.properties = everything the Android BUILD needs (no signing private key in it)."""
    priv, aes = load_keys(keys_dir)
    pub = priv.public_key().public_bytes(serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo)
    lines = [
        "# GENERATED by tools/y9tool.py. NEVER upload this file (it is in .gitignore).",
        f"config_url={read(os.path.join(keys_dir, 'config_url.txt')).strip()}",
        f"sign_public_key={b64(pub)}",
        f"aes_key={b64(aes)}",
        f"keystore_b64={b64(read(os.path.join(keys_dir, 'release.p12'), 'rb'))}",
        f"keystore_password={read(os.path.join(keys_dir, 'release.password')).strip()}",
    ]
    write_secret(props_path, "\n".join(lines) + "\n")


def cmd_init(a):
    url = a.config_url or (f"https://raw.githubusercontent.com/{a.repo}/main/site/config.enc.json" if a.repo else None)
    if not url:
        sys.exit("Give --repo USER/REPO (or --config-url URL).")
    priv_path = os.path.join(a.keys, "sign_private.pem")
    if os.path.exists(priv_path) and not a.force:
        sys.exit("Keys already exist. Use --force only if you accept that every old config/APK signature stops working.")
    os.makedirs(a.keys, exist_ok=True)

    # 1) config signing key (ECDSA P-256) + config encryption key (AES-256)
    priv = ec.generate_private_key(ec.SECP256R1())
    write_secret(priv_path, priv.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                                               serialization.NoEncryption()).decode())
    write_secret(os.path.join(a.keys, "aes.key"), b64(os.urandom(32)))
    write_secret(os.path.join(a.keys, "config_url.txt"), url)

    # 2) APK signing keystore: a STABLE key is what lets users update the app in place
    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, "Y9 PRO V5")])
    now = datetime.datetime.now(datetime.timezone.utc)
    cert = (x509.CertificateBuilder().subject_name(name).issuer_name(name).public_key(key.public_key())
            .serial_number(x509.random_serial_number())
            .not_valid_before(now - datetime.timedelta(days=1))
            .not_valid_after(now + datetime.timedelta(days=365 * 30))
            .sign(key, hashes.SHA256()))
    pw = base64.urlsafe_b64encode(os.urandom(18)).decode()
    enc = (serialization.PrivateFormat.PKCS12.encryption_builder()
           .kdf_rounds(50000).key_cert_algorithm(pkcs12.PBES.PBESv1SHA1And3KeyTripleDESCBC)
           .hmac_hash(hashes.SHA1()).build(pw.encode()))
    write_secret(os.path.join(a.keys, "release.p12"),
                 pkcs12.serialize_key_and_certificates(b"y9", key, cert, None, enc), "wb")
    write_secret(os.path.join(a.keys, "release.password"), pw)

    make_props(a.keys, a.props)
    print(f"Config URL : {url}")
    print(f"Created ./{a.keys}/ and {a.props}")
    print("BACK UP the whole keys/ folder somewhere private. Never upload keys/ or keys.properties.")


def cmd_props(a):
    make_props(a.keys, a.props)
    print("Wrote", a.props)


def cmd_set_password(a):
    pw = os.environ.get("Y9_PASSWORD")
    if not pw:
        pw = getpass.getpass("New password: ")
        if pw != getpass.getpass("Repeat: "):
            sys.exit("Passwords do not match.")
    if len(pw) < 8:
        sys.exit("Use at least 8 characters.")
    salt = os.urandom(16)
    h = hashlib.pbkdf2_hmac("sha256", pw.encode("utf-8"), salt, PBKDF2_ITERATIONS, 32)
    with open(a.config, encoding="utf-8") as f:
        cfg = json.load(f)
    cfg["password"] = {"salt": b64(salt), "iter": PBKDF2_ITERATIONS, "hash": b64(h)}
    with open(a.config, "w", encoding="utf-8") as f:
        json.dump(cfg, f, ensure_ascii=False, indent=2)
    print("Password hash saved in", a.config, "(the plain password is not stored anywhere).")
    print("Users who entered the old password will be asked again after the next build/upload.")


def cmd_build(a):
    priv, aes = load_keys(a.keys)
    with open(a.config, encoding="utf-8") as f:
        cfg = json.load(f)
    pw = cfg.get("password") or {}
    if not (pw.get("hash") and pw.get("salt")):
        sys.exit("No password set yet. Run: set-password " + a.config)
    plain = json.dumps(cfg, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    seq = int(time.time())
    iv = os.urandom(12)
    ct = AESGCM(aes).encrypt(iv, plain, None)  # ciphertext || 16-byte tag
    iv_b, ct_b = b64(iv), b64(ct)
    sig = priv.sign(f"y9v5.{seq}.{iv_b}.{ct_b}".encode(), ec.ECDSA(hashes.SHA256()))  # DER
    env = {"v": 1, "seq": seq, "iv": iv_b, "ct": ct_b, "sig": b64(sig)}
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, "w") as f:
        json.dump(env, f, separators=(",", ":"))
    print(f"Built {a.out} (seq={seq}). This is the only generated file that goes to GitHub.")


def cmd_open(a):
    priv, aes = load_keys(a.keys)
    with open(a.file) as f:
        env = json.load(f)
    data = f"y9v5.{env['seq']}.{env['iv']}.{env['ct']}".encode()
    priv.public_key().verify(base64.b64decode(env["sig"]), data, ec.ECDSA(hashes.SHA256()))
    plain = AESGCM(aes).decrypt(base64.b64decode(env["iv"]), base64.b64decode(env["ct"]), None)
    print("signature OK")
    print(json.dumps(json.loads(plain), ensure_ascii=False, indent=2))


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--keys", default="keys")
    s = p.add_subparsers(dest="cmd", required=True)
    i = s.add_parser("init")
    i.add_argument("--repo", help="GITHUB_USER/REPO_NAME")
    i.add_argument("--config-url")
    i.add_argument("--props", default="keys.properties")
    i.add_argument("--force", action="store_true")
    i.set_defaults(fn=cmd_init)
    pr = s.add_parser("props"); pr.add_argument("--props", default="keys.properties"); pr.set_defaults(fn=cmd_props)
    sp = s.add_parser("set-password"); sp.add_argument("config"); sp.set_defaults(fn=cmd_set_password)
    b = s.add_parser("build"); b.add_argument("config"); b.add_argument("--out", default="site/config.enc.json")
    b.set_defaults(fn=cmd_build)
    o = s.add_parser("open"); o.add_argument("file"); o.set_defaults(fn=cmd_open)
    a = p.parse_args()
    a.fn(a)


if __name__ == "__main__":
    main()
